// ponte_webhook: an outbound webhook subscription (Settings → Webhooks). The signing secret is
// generated by Ponte on create, returned once, and kept in state as a sensitive attribute so a
// SIEM module can read it from the same configuration.

type webhookResource struct {
	c *client.Client
}

type webhookModel struct {
	ID            types.String `tfsdk:"id"`
	Name          types.String `tfsdk:"name"`
	URL           types.String `tfsdk:"url"`
	EventTypes    types.List   `tfsdk:"event_types"`
	Headers       types.Map    `tfsdk:"headers"`
	Description   types.String `tfsdk:"description"`
	Enabled       types.Bool   `tfsdk:"enabled"`
	Format        types.String `tfsdk:"format"`
	FormatConfig  types.String `tfsdk:"format_config"`
	MinSeverity   types.String `tfsdk:"min_severity"`
	SigningSecret types.String `tfsdk:"signing_secret"`
}

func newWebhookResource() resource.Resource { return &webhookResource{} }

func (r *webhookResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_webhook"
}

func (r *webhookResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "An outbound webhook subscription: platform events (authz decisions, receipt.issued, alerts, …) delivered to a URL, HMAC-signed. Format ponte (the envelope) or udm (Google SecOps).",
		Attributes: map[string]schema.Attribute{
			"id":            schema.StringAttribute{Computed: true, PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},
			"name":          schema.StringAttribute{Required: true},
			"url":           schema.StringAttribute{Required: true, Description: "https URL; private targets are refused in production."},
			"event_types":   schema.ListAttribute{ElementType: types.StringType, Required: true, Description: "Event types, or [\"*\"] for all. GET /api/v1/webhooks/event-types lists them."},
			"headers":       schema.MapAttribute{ElementType: types.StringType, Optional: true, Sensitive: true, Description: "Headers sent on every delivery (an Authorization header, for example). Not read back from the api."},
			"description":   schema.StringAttribute{Optional: true, Computed: true, Default: stringdefault.StaticString("")},
			"enabled":       schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(true)},
			"format":        schema.StringAttribute{Optional: true, Computed: true, Default: stringdefault.StaticString("ponte"), Description: "ponte or udm."},
			"min_severity":  schema.StringAttribute{Optional: true, Computed: true, Default: stringdefault.StaticString("high"), Description: "Lowest level of security finding (governance.alert) delivered: critical, high or medium. Other event types are not filtered. Low findings are never sent."},
			"format_config": schema.StringAttribute{Optional: true, Description: "JSON overrides for the udm mapping (event_type_map, product_name, vendor_name, default_event_type)."},
			"signing_secret": schema.StringAttribute{Computed: true, Sensitive: true, Description: "The HMAC secret Ponte signs deliveries with (X-Ponte-Signature). Returned once on create.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},
		},
	}
}

func (r *webhookResource) Configure(_ context.Context, req resource.ConfigureRequest, _ *resource.ConfigureResponse) {
	r.c = clientFrom(req.ProviderData)
}

func (m *webhookModel) input(ctx context.Context) client.WebhookInput {
	in := client.WebhookInput{Name: m.Name.ValueString(), URL: m.URL.ValueString(), Description: m.Description.ValueString(), Format: m.Format.ValueString(), MinSeverity: m.MinSeverity.ValueString(), EventTypes: []string{}, Headers: map[string]string{}}
	_ = m.EventTypes.ElementsAs(ctx, &in.EventTypes, false)
	if !m.Headers.IsNull() && !m.Headers.IsUnknown() {
		_ = m.Headers.ElementsAs(ctx, &in.Headers, false)
	}
	enabled := m.Enabled.ValueBool()
	in.Enabled = &enabled
	if s := m.FormatConfig.ValueString(); s != "" {
		in.FormatConfig = json.RawMessage(s)
	}
	return in
}

// fill refreshes what the api reports; headers and the secret stay as in state.
func (m *webhookModel) fill(ctx context.Context, w *client.Webhook) {
	m.ID = types.StringValue(w.ID)
	m.Name = types.StringValue(w.Name)
	m.URL = types.StringValue(w.URL)
	m.Description = types.StringValue(w.Description)
	m.Enabled = types.BoolValue(w.Enabled)
	f := w.Format
	if f == "" {
		f = "ponte"
	}
	m.Format = types.StringValue(f)
	sev := w.MinSeverity
	if sev == "" {
		sev = "high" // an api that predates the field delivers critical and high
	}
	m.MinSeverity = types.StringValue(sev)
	ev, _ := types.ListValueFrom(ctx, types.StringType, w.EventTypes)
	if len(w.EventTypes) == 0 {
		ev, _ = types.ListValueFrom(ctx, types.StringType, []string{})
	}
	m.EventTypes = ev
}

func (r *webhookResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan webhookModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	w, secret, err := r.c.CreateWebhook(ctx, plan.input(ctx))
	if err != nil {
		resp.Diagnostics.AddError("Creating the webhook failed", err.Error())
		return
	}
	plan.fill(ctx, w)
	plan.SigningSecret = types.StringValue(secret)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *webhookResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state webhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	w, err := r.c.GetWebhook(ctx, state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Reading the webhook failed", err.Error())
		return
	}
	state.fill(ctx, w)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *webhookResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state webhookModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.c.UpdateWebhook(ctx, state.ID.ValueString(), plan.input(ctx)); err != nil {
		resp.Diagnostics.AddError("Updating the webhook failed", err.Error())
		return
	}
	w, err := r.c.GetWebhook(ctx, state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Reading the webhook failed", err.Error())
		return
	}
	plan.fill(ctx, w)
	plan.SigningSecret = state.SigningSecret
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *webhookResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state webhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.c.DeleteWebhook(ctx, state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Deleting the webhook failed", err.Error())
	}
}

func (r *webhookResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	w, err := r.c.GetWebhook(ctx, req.ID)
	if err != nil {
		resp.Diagnostics.AddError("Reading the webhook failed", err.Error())
		return
	}
	var m webhookModel
	m.fill(ctx, w)
	m.SigningSecret = types.StringValue("") // only ever shown on create
	// The api does not return headers (they may carry a credential) or the format overrides:
	// they are null until the configuration sets them. A typed null, or the state cannot be
	// written at all ("Value Conversion Error", found importing on a real stack).
	m.Headers = types.MapNull(types.StringType)
	m.FormatConfig = types.StringNull()
	resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
}
